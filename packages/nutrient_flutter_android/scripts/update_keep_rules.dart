// Regenerates the block of android/consumer-rules.pro between the
// `BEGIN GENERATED` and `END GENERATED` markers from the JNI bindings.
//
// The bindings look up Nutrient Android SDK methods by name and JNI signature.
// Those signatures name AndroidX, Kotlin, Flutter and other library classes,
// and if R8 renames one in an app's release build, every method that takes or
// returns it fails with NoSuchMethodError. The block keeps the names of every
// such class: each `L...;` type in the bindings' signatures that isn't an
// Android framework class (never renamed), a Nutrient SDK class (kept by the
// SDK's own rules) or a plugin class (kept by hand above the block).
//
// generate_bindings.sh runs this after every regeneration, and CI runs it with
// --check (bin/ci-plugin-analyze.sh), so the block can't fall behind.
//
// Usage, from anywhere:
//   dart scripts/update_keep_rules.dart           # rewrite the block
//   dart scripts/update_keep_rules.dart --check   # exit 1 if it's stale
//   dart scripts/update_keep_rules.dart --mapping <app>/build/app/outputs/mapping/release/mapping.txt
//       # exit 1 if that R8 release build renamed a class the bindings name,
//       # or removed one they need (bin/ci-android-catalog-build.sh)

import 'dart:io';

const _bindingsPath = 'lib/src/bindings/nutrient_android_sdk_bindings.dart';
const _rulesPath = 'android/consumer-rules.pro';

const _beginMarker =
    '# BEGIN GENERATED by scripts/update_keep_rules.dart. Do not edit by hand.';
const _endMarker = '# END GENERATED';

const _pluginPackage = 'com.nutrient.nutrient_flutter_android.';

// Classes R8 never renames (they're in android.jar, not the app), and classes
// other rules files already keep: the Nutrient SDK's, and the plugins' own,
// which `nutrient_flutter` and this package keep by hand.
const _excludedPrefixes = [
  'android.',
  'dalvik.',
  'java.',
  'javax.',
  'org.apache.http.',
  'org.json.',
  'org.w3c.dom.',
  'org.xml.sax.',
  'org.xmlpull.v1.',
  'com.pspdfkit.',
  'io.nutrient.',
  _pluginPackage,
];

// A class type in a JNI signature: `Landroidx/fragment/app/Fragment;`.
final _classType = RegExp(r'L([A-Za-z_][\w$]*(?:/[\w$]+)+);');
// A class name passed to JClass.forName: `com/pspdfkit/ui/PdfFragment`.
final _className = RegExp(r'^[a-z][\w$]*(?:/[\w$]+)+$');
// jnigen writes every signature and class name as a raw string literal.
final _rawString = RegExp(r"r'([^']*)'");

// Classes the app needs whether or not the bindings name them: the Nutrient
// SDK looks io.flutter.BuildConfig up by name to confirm it runs in Flutter.
const _requiredClasses = ['io.flutter.BuildConfig'];

void main(List<String> args) {
  final check = args.length == 1 && args[0] == '--check';
  final mapping =
      args.length == 2 && args[0] == '--mapping' ? File(args[1]) : null;
  if (args.isNotEmpty && !check && mapping == null) {
    stderr.writeln(
      'Usage: dart scripts/update_keep_rules.dart '
      '[--check | --mapping <mapping.txt>]',
    );
    exit(64);
  }

  final packageDir = File.fromUri(Platform.script).parent.parent;
  final bindings = File('${packageDir.path}/$_bindingsPath');
  final rules = File('${packageDir.path}/$_rulesPath');

  final referenced = <String>{};
  for (final literal in _rawString.allMatches(bindings.readAsStringSync())) {
    final value = literal.group(1)!;
    if (_className.hasMatch(value)) referenced.add(value.replaceAll('/', '.'));
    for (final type in _classType.allMatches(value)) {
      referenced.add(type.group(1)!.replaceAll('/', '.'));
    }
  }

  if (mapping != null) {
    _checkMapping(mapping, referenced);
    return;
  }

  final text = rules.readAsStringSync();
  final begin = text.indexOf(_beginMarker);
  final end = text.indexOf(_endMarker);
  if (begin < 0 || end < begin) {
    _fail('$_rulesPath has no "$_beginMarker" ... "$_endMarker" block.');
  }
  final handWritten = text.substring(0, begin) + text.substring(end);

  // Plugin classes need -keep, not -keepnames: R8 sees no caller of them at
  // all, so it would remove them, not just rename them. Those rules are
  // written by hand, so only check they're there.
  final unkeptPluginClasses = [
    for (final name in referenced)
      if (name.startsWith(_pluginPackage) &&
          !RegExp(
            '^-keep class ${RegExp.escape(name)}(?:[ {]|\$)',
            multiLine: true,
          ).hasMatch(handWritten))
        name,
  ]..sort();
  if (unkeptPluginClasses.isNotEmpty) {
    _fail(
      'The bindings call these plugin classes, but $_rulesPath has no '
      '`-keep class` rule for them:\n'
      '${unkeptPluginClasses.map((c) => '  $c').join('\n')}',
    );
  }

  final kept = [
    for (final name in referenced)
      if (!_excludedPrefixes.any(name.startsWith)) name,
  ]..sort();
  final block = [
    _beginMarker,
    for (final name in kept) '-keepnames class $name { *; }',
    '',
  ].join('\n');

  final current = text.substring(begin, end);
  if (current == block) {
    stdout.writeln(
      '$_rulesPath: generated keep rules are up to date '
      '(${kept.length} classes).',
    );
    return;
  }

  if (check) {
    final currentNames = RegExp(
      r'^-keepnames class (\S+)',
      multiLine: true,
    ).allMatches(current).map((m) => m.group(1)!).toSet();
    final changes = [
      for (final n in kept)
        if (!currentNames.contains(n)) '  + $n',
      for (final n in currentNames)
        if (!kept.contains(n)) '  - $n',
    ];
    _fail(
      '$_rulesPath is out of date with the JNI bindings.\n'
      '${changes.map((c) => '$c\n').join()}'
      'Run `dart scripts/update_keep_rules.dart` in nutrient_flutter_android '
      'and commit the result.',
    );
  }

  rules.writeAsStringSync(
    text.substring(0, begin) + block + text.substring(end),
  );
  stdout.writeln('$_rulesPath: wrote ${kept.length} generated keep rules.');
}

// R8's mapping.txt lists every class in the output, renamed or not, as
// `original.Name -> new.Name:`. A class the bindings name must keep its name;
// one that's missing is fine (the app doesn't use it), unless the plugin's
// Dart code calls it directly or it's on the required list.
void _checkMapping(File mapping, Set<String> referenced) {
  final renamedTo = <String, String>{};
  final classLine = RegExp(r'^(\S+) -> (\S+):$');
  for (final line in mapping.readAsLinesSync()) {
    final m = classLine.firstMatch(line);
    if (m != null) renamedTo[m.group(1)!] = m.group(2)!;
  }
  final problems = [
    for (final name in referenced.toList()..sort())
      if (renamedTo.containsKey(name) && renamedTo[name] != name)
        '  $name was renamed to ${renamedTo[name]}',
    for (final name in [
      ..._requiredClasses,
      ...referenced.where((n) => n.startsWith(_pluginPackage)),
    ])
      if (!renamedTo.containsKey(name)) '  $name was removed',
  ];
  if (problems.isNotEmpty) {
    _fail(
      'R8 renamed or removed classes the JNI bindings reach by name '
      '(${mapping.path}):\n${problems.join('\n')}\n'
      'Keep them in android/consumer-rules.pro.',
    );
  }
  final present = referenced.where(renamedTo.containsKey).length;
  stdout.writeln(
    '${mapping.path}: R8 kept the names of all $present classes '
    'the bindings name that are in the app.',
  );
}

Never _fail(String message) {
  stderr.writeln('ERROR: $message');
  exit(1);
}
